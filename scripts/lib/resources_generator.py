@dataclass
class ResourcesPlan:
    """How to build / fall back the three resources sub-regions for a
    generate-mode compile.

    ``pictures`` are generated when present; ``font_region`` and the fixed
    bootloader/driver prefix are always taken from the reference (fonts
    are infeasible; the prefix is not project content).  ``feasible`` is
    True only when EVERY requested sub-region can be produced byte-exact —
    callers MUST fall back to the reference resources blob otherwise so the
    byte-identical compilers never regress.
    """
    pictures: list[PictureEntry] = field(default_factory=list)
    fonts_generated: bool = False
    feasible: bool = False


def plan_resources(picture_images: list[Image.Image]) -> ResourcesPlan:
    """Decide what the resources generator can produce byte-exact.

    Pictures are always generable.  Fonts never are (the editor rasterizer
    wall).  So a fully-generated resources region is feasible ONLY when the
    project has no fonts that would need regenerating — which is never true
    for a real F-series project (every one ships ≥1 ``.zi``).  Hence
    :attr:`ResourcesPlan.feasible` is essentially always False and the
    caller copies the reference blob; the picture entries are still exposed
    for callers that want to splice JUST the picture sub-region.
    """
    pics = [build_picture_block(im, i) for i, im in enumerate(picture_images)]
    # Fonts can't be regenerated byte-exact, so a whole-region generate is
    # not feasible.  (If a project ever had zero fonts the plan could flip,
    # but no such F-series project exists.)
    return ResourcesPlan(pictures=pics, fonts_generated=False, feasible=False)


