"""resources_generator — from-scratch generation of the TFT *resources
region* (pictures, fonts, and the resources-coupled descriptors).

This is the last span the HMI→TFT compiler still copies verbatim from a
reference ``.tft`` (the prefix ``0x10000``..``0x70000``; see
``compile_hmi`` and ``findings/format-tft.md`` §"Resources section").
The region holds three kinds of project content plus a large fixed
bootloader/driver blob:

  1. **Pictures** — RGB565 images referenced by Picture components.
  2. **Fonts** — concatenated ``.zi`` bitmap fonts.
  3. **Resources-coupled descriptors** — the ``picxinxi`` / ``zimoxinxi``
     index tables and the ``appinf1`` fields that point at them.

Honest capability per sub-part (see ``findings/format-zi.md``,
``findings/format-tft.md`` and the verdict block at the bottom of this
file):

  * **Pictures — VERIFIED byte-exact.**  :func:`build_picture_region`
    reproduces the ``15_picture`` fixture's picxinxi record + pixel block
    byte-for-byte from a PIL image.  RGB565 truncation (``>>3``/``>>2``/
    ``>>3``) is stable, so a re-encode of the editor's own pixels is
    identical; the per-picture block is a 20-byte zero header + ``W·H·2``
    RGB565-LE pixels.

  * **Resources-coupled descriptors — VERIFIED (offsets) / partial
    (the ``0x48b5d`` base).**  The picxinxi/zimoxinxi *table contents* and
    the appinf1 offset/count fields are derived from the picture/font
    composition (``compute_appinf1`` already covers the appinf1 side and
    is tested against 5 fixtures).  The one non-derivable input is
    ``picxinxi_offset_in_resources`` (``0x48b5d`` in every fixture) — a
    property of the *fixed* bootloader/driver/GB2312-index blob that
    precedes the project content, not of the project itself.  It stays a
    caller-supplied constant taken from the reference.

  * **Fonts (``.zi`` rasterization) — INFEASIBLE byte-exact (the hard
    wall).**  The header, codepage ranges, glyph-index (character map)
    structure and per-glyph *metrics* (advance width, kerning) ARE
    reproducible and are locked as golden by :func:`describe_zi_font`.
    The per-glyph **pixel data** is not: the editor's glyphs are 3-bit
    anti-aliased (mode ``0x03``) and even with a per-glyph best-fit
    alignment sweep (size, baseline, x-offset) a headless freetype/PIL
    rasterization of the same Liberation TTF matches only ~82% of alpha
    cells and **0 glyphs exactly**.  The residual is the editor's own
    rasterizer (its hinting, AA ramp and sub-pixel positioning), which is
    not reproducible from the public font + format alone.  So font
    generation FALLS BACK to the reference blob; this is recorded as a
    won't-fix-by-design recommendation for me/miata-dash#39.

Public surface:

    encode_rgb565(img)                  -> bytes        (W·H·2, LE)
    build_picture_block(img, ...)       -> PictureEntry (record + pixels)
    build_picture_region(entries)       -> bytes        (records ‖ pixels)
    picture_from_rgb565(px, w, h)       -> PIL.Image     (decode helper)
    describe_zi_font(zi_bytes)          -> ZiDescriptor  (reproducible part)
    FONT_RASTER_FEASIBLE                = False
    PICTURE_GEN_FEASIBLE               = True
"""
from __future__ import annotations

import struct
from dataclasses import dataclass, field
from typing import Optional

from PIL import Image


# ── Capability flags (consumed by compile_hmi's optional generate-mode) ──
PICTURE_GEN_FEASIBLE: bool = True
"""Picture region can be generated byte-exact from a source image."""

FONT_RASTER_FEASIBLE: bool = False
"""``.zi`` glyph *pixel data* cannot be byte-matched headlessly — the
editor's AA rasterizer is not reproducible.  Font generation always falls
back to the reference resources blob.  See the module docstring + the
verdict block below."""


# ── Picture format constants (verified against 15_picture) ───────────────
PICXINXI_RECORD_SIZE: int = 24
PICTURE_BLOCK_HEADER: int = 20
"""Each picture's pixel block is prefixed by a 20-byte zero header before
the ``W·H·2`` RGB565-LE pixels.  ``imgbytesize`` (picxinxi +16) ==
``PICTURE_BLOCK_HEADER + W·H·2``."""


# =========================================================================
# Sub-part 1 — Pictures (RGB565).  VERIFIED byte-exact vs 15_picture.
# =========================================================================

def encode_rgb565(img: Image.Image) -> bytes:
    """Encode a PIL image to RGB565 little-endian bytes (``W·H·2``).

    Channel truncation is ``r>>3 / g>>2 / b>>3`` — the standard 8→5/6/5
    fold.  This is the exact transform the editor applies; verified
    against ``15_picture`` (a round-trip of the editor's own pixels is
    byte-identical, because the truncation is idempotent over already-565
    values bit-replicated to 8-bit).
    """
    rgb = img.convert("RGB")
    w, h = rgb.size
    px = rgb.load()
    out = bytearray(w * h * 2)
    i = 0
    for y in range(h):
        for x in range(w):
            r, g, b = px[x, y]
            v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            out[i] = v & 0xFF
            out[i + 1] = (v >> 8) & 0xFF
            i += 2
    return bytes(out)


def picture_from_rgb565(px: bytes, w: int, h: int) -> Image.Image:
    """Decode a raw RGB565-LE pixel block to a PIL RGB image.

    Uses bit-replication (``v<<3 | v>>2`` for 5-bit channels, ``v<<2 |
    v>>4`` for the 6-bit green).  The resulting RGB888 re-encodes to the
    identical RGB565 via :func:`encode_rgb565`, so this is the inverse
    used by the verification test (decode the editor's pixels, feed them
    back through the generator, expect byte-identity)."""
    img = Image.new("RGB", (w, h))
    out = img.load()
    i = 0
    for y in range(h):
        for x in range(w):
            v = px[i] | (px[i + 1] << 8)
            i += 2
            r5 = (v >> 11) & 0x1F
            g6 = (v >> 5) & 0x3F
            b5 = v & 0x1F
            out[x, y] = (
                (r5 << 3) | (r5 >> 2),
                (g6 << 2) | (g6 >> 4),
                (b5 << 3) | (b5 >> 2),
            )
    return img


@dataclass
class PictureEntry:
    """A generated picture: its 24-byte picxinxi index record and the
    pixel block (20-byte header + RGB565 pixels)."""
    record: bytes        # 24 bytes (placed in the picxinxi table)
    pixels: bytes        # PICTURE_BLOCK_HEADER + W·H·2 bytes
    width: int
    height: int

    @property
    def imgbytesize(self) -> int:
        return len(self.pixels)


def build_picture_block(
    img: Image.Image,
    pictureid: int = 0,
    *,
    qumo: int = 10,
    quality: int = 100,
    alphaen: int = 1,
    picdatatype: int = 3,
    encodeen: int = 0,
    alphaaddr: int = 0,
    pixeldata_offset: int = PICXINXI_RECORD_SIZE,
) -> PictureEntry:
    """Build one picture's index record + pixel block from a PIL image.

    The picxinxi record layout (24 B, verified against ``15_picture``):

        +0  u8   qumo            (0x0a in the fixture)
        +1  u8   quality         (0x64 = 100)
        +2  u8   alphaen         (1 = alpha header present)
        +3  u8   picdatatype     (3 = RGB565 + 20-byte header)
        +4  u16  pictureid
        +6  u8   encodeen
        +7  u8   res             (0)
        +8  u32  pixeldata_off   (offset from the record to its pixels;
                                  for one picture this is 24 = the record
                                  size — see note below)
        +12 u16  width
        +14 u16  height
        +16 u32  imgbytesize     (= 20 + W·H·2)
        +20 i32  alphaaddr       (0 when inline)

    The defaults reproduce the ``15_picture`` record exactly.  ``qumo`` /
    ``quality`` / ``picdatatype`` are editor knobs; ``picdatatype=3`` is
    the only mode this writer emits (uncompressed RGB565 + a zero header),
    matching every observed F-series fixture.
    """
    rgb = img.convert("RGB")
    w, h = rgb.size
    pixels = b"\x00" * PICTURE_BLOCK_HEADER + encode_rgb565(rgb)
    imgbytesize = len(pixels)
    record = bytearray(PICXINXI_RECORD_SIZE)
    record[0] = qumo & 0xFF
    record[1] = quality & 0xFF
    record[2] = alphaen & 0xFF
    record[3] = picdatatype & 0xFF
    struct.pack_into("<H", record, 4, pictureid & 0xFFFF)
    record[6] = encodeen & 0xFF
    record[7] = 0
    struct.pack_into("<I", record, 8, pixeldata_offset & 0xFFFFFFFF)
    struct.pack_into("<H", record, 12, w & 0xFFFF)
    struct.pack_into("<H", record, 14, h & 0xFFFF)
    struct.pack_into("<I", record, 16, imgbytesize)
    struct.pack_into("<i", record, 20, alphaaddr)
    return PictureEntry(bytes(record), bytes(pixels), w, h)


def build_picture_region(entries: list[PictureEntry]) -> bytes:
    """Lay out the picture region: all 24-byte index records first, then
    every pixel block contiguously (matching the resources-region order
    ``picxinxiadd`` → records → pixel data → ``zimoxinxiadd``).

    For the single-picture case the in-record ``pixeldata_offset`` field
    (24) is already correct.  For N pictures the per-record offset points
    from each record to its own pixels (records are packed first, so
    picture *k*'s pixels begin at ``24·N + Σ_{j<k} imgbytesize_j``);
    callers that need multi-picture parity should set ``pixeldata_offset``
    on each entry accordingly.  No multi-picture editor fixture exists to
    verify that field's exact convention, so it is left caller-controlled.
    """
    records = b"".join(e.record for e in entries)
    pixels = b"".join(e.pixels for e in entries)
    return records + pixels


# =========================================================================
# Sub-part 3 — Fonts (.zi).  Reproducible part locked; pixels INFEASIBLE.
# =========================================================================

@dataclass
class ZiGlyphMetric:
    """Per-glyph metrics that ARE reproducible from the font + format
    alone (everything except the rasterized pixel stream)."""
    codepoint: int
    width: int           # advance width (px)
    klft: int            # left kerning
    krht: int            # right kerning
    data_len: int        # bytes the glyph's pixel stream occupies
    mode: Optional[int]  # 0x01 B&W / 0x03 AA / None if empty


@dataclass
class ZiDescriptor:
    """The byte-exactly-reproducible structure of a ``.zi`` font: header
    fields, codepage ranges, name, and the glyph-index (character map)
    metrics.  The per-glyph *pixel data* is intentionally NOT held here —
    it is the part the editor's rasterizer makes non-reproducible."""
    version: int
    encoding: int
    width: int           # declared cell width (0 = variable)
    height: int          # cell height
    name: str
    cp_first_start: int
    cp_first_end: int
    cp_second_start: int
    cp_second_end: int
    glyph_count: int
    metrics: list[ZiGlyphMetric] = field(default_factory=list)
    aa_glyphs: int = 0   # count of glyphs using AA mode 0x03
    bw_glyphs: int = 0   # count of glyphs using B&W mode 0x01


def describe_zi_font(zi_bytes: bytes) -> ZiDescriptor:
    """Parse a standalone ``.zi`` blob and extract the structurally
    reproducible descriptor (header + codepage + per-glyph metrics).

    This is what a from-scratch font writer CAN reproduce byte-exact.
    The pixel streams are deliberately left out — see
    :data:`FONT_RASTER_FEASIBLE` and the module docstring.  Used to lock a
    golden snapshot in the test suite.
    """
    from sim.font import _parse_header, _codepoints_for

    hdr = _parse_header(zi_bytes)
    cps = _codepoints_for(hdr)
    cm = hdr["data_start"]
    nchars = hdr["nchars"]
    name_off = hdr["name_off"]
    name_len = hdr["name_len"]
    name = (
        zi_bytes[name_off:name_off + name_len]
        .decode("latin-1", errors="replace")
        .rstrip("\x00")
    )

    metrics: list[ZiGlyphMetric] = []
    aa = bw = 0
    if hdr["version"] in (5, 6):
        align8 = hdr.get("align8", 0)
        for i, cp in enumerate(cps[:nchars]):
            off = cm + i * 10
            if off + 10 > len(zi_bytes):
                break
            entry = zi_bytes[off:off + 10]
            gw = entry[2]
            klft = entry[3]
            krht = entry[4]
            doff = entry[5] | (entry[6] << 8) | (entry[7] << 16)
            if align8 & 0x01:
                doff *= 8
            dlen = struct.unpack_from("<H", entry, 8)[0]
            mode = None
            if gw and dlen:
                abs_off = cm + doff
                if abs_off < len(zi_bytes):
                    mode = zi_bytes[abs_off]
                    if mode == 0x03:
                        aa += 1
                    elif mode == 0x01:
                        bw += 1
            metrics.append(ZiGlyphMetric(cp, gw, klft, krht, dlen, mode))

    return ZiDescriptor(
        version=hdr["version"],
        encoding=hdr["encoding"],
        width=hdr["width"],
        height=hdr["height"],
        name=name,
        cp_first_start=hdr["cp_first_start"],
        cp_first_end=hdr["cp_first_end"],
        cp_second_start=hdr["cp_second_start"],
        cp_second_end=hdr["cp_second_end"],
        glyph_count=nchars,
        metrics=metrics,
        aa_glyphs=aa,
        bw_glyphs=bw,
    )


