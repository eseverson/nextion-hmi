"""objxinxi_encoder — generate the per-component objxinxi entry (232 B).

Each component (and the page pseudo-component) gets one 232-byte entry in
the objxinxi table (file offset ``appinf1.objxinxiadd``).  The entry's
*header* (first 56 bytes) is decoded in
``scripts/lib/tft_attrs.ObjxinxiEntry`` / ``findings/attribute-records.md``:

    +0   u8   lei              (component type code)
    +1   u8   id               (instance id)
    +2   u8   const 0x00
    +3   u8   type-flag        (per-class; see TYPE_FLAG below)
    +4   u32  init_off         (slot-0 / Ref bytecode offset; BACK-PATCH)
    +8   u32  event slot 1     (BACK-PATCH)
    +12  u32  event slot 2     (BACK-PATCH)
    +16  u32  event slot 3     (BACK-PATCH)
    +20  u32  event slot 4     (BACK-PATCH)
    +24  u32  event slot 5     (BACK-PATCH)
    +28  u32  objdatarampos    (media-blob offset; per-page ALLOCATOR)
    +32  u32  const 0x007f0000
    +36  u32  const 0
    +40  u16  x
    +42  u16  y
    +44  u16  w
    +46  u16  h
    +48  u16  endx  (= x + w - 1, clamped)
    +50  u16  endy  (= y + h - 1, clamped)
    +52  u32  attstr_bytecode_offset  (Attstrpianyi head; BACK-PATCH)
    +56  88×u16  attstr slot table → page binattinf record indices, or 0xffff

``+52`` (``attstr_bytecode_offset``) equals ``init_off`` *only* when the
component has a slot-0 init block (the init block is then the first thing
in the component's bytecode span).  When slot 0 is absent (Hotspot,
Timer, Variable) it is a distinct strdata-relative offset — for Hotspot
it is the length-prefix of the first present event chain, for Variable it
points just before the page media blob.  It is therefore carried as its
own back-patch input, not derived from ``init_off``.

This module generates the **fully HMI-derivable** fields (lei, id, the two
constants, the type-flag, and the geometry) and accepts the
allocator/back-patch-dependent fields (``init_off``, the 6 event slot
offsets, ``objdatarampos``, and the 88-slot attstr table) as inputs.  That
draws a precise line: everything *except* those four input groups is
generated here byte-for-byte; the inputs are produced by the per-page
media allocator (``objdatarampos``), the second-pass offset back-patcher
(``init_off`` + slots — work-item #3), and the binattinf generator (attstr
slot table — work-item #2c).

Verified byte-for-byte against ``source/nextion.hmi.tft`` (all 39 entries)
by ``tests/sim/test_objxinxi_encoder.py``.
"""
from __future__ import annotations

import struct
from dataclasses import dataclass, field


OBJXINXI_ENTRY_SIZE = 232
ATTSTR_SLOT_OFFSET = 56
ATTSTR_SLOT_COUNT = 88

# Header constants observed identical across every entry in the project.
CONST_AT_2 = 0x00          # +2 (the +3 byte is the per-class type-flag)
CONST_AT_32 = 0x007F0000   # +32 u32
CONST_AT_36 = 0x00000000   # +36 u32

# Per-class type-flag byte at +3.  Decoded from source/nextion.hmi.tft:
#   0x37 — visible / touchable components (Page, XFloat, Text, Prog,
#          Hotspot, Slider, Button) and the page pseudo-component.
#   0x27 — Timer (lei 51): non-visual, event-bearing.
#   0x07 — Variable (lei 52): non-visual, no events.
# The flag is a function of component class only (a bitfield the editor
# sets from xiliexinxitype properties — visible/has-event/in-memory).
TYPE_FLAG: dict[int, int] = {
    121: 0x37,  # Page
    59:  0x37,  # XFloat
    116: 0x37,  # Text
    106: 0x37,  # Prog
    109: 0x37,  # Hotspot
    1:   0x37,  # Slider
    98:  0x37,  # Button
    51:  0x27,  # Timer
    52:  0x07,  # Variable
}

# Geometry default for non-visual components (Timer / Variable): the
# editor stores a 1×1 box at the origin.  endx/endy clamp to 0.
NONVISUAL_LEIS = frozenset({51, 52})

SENTINEL = 0xFFFFFFFF


@dataclass
class ObjxinxiInputs:
    """The allocator / back-patch dependent fields for one entry.

    Everything here is *not* derivable from the HMI alone:

      * ``init_off`` / ``slot_offsets`` — strdata-relative bytecode
        offsets, only known after the usercode layout is fixed
        (work-item #3 back-patch).  Use ``SENTINEL`` (0xffffffff) for an
        absent slot.
      * ``objdatarampos`` — the component's offset into the page media
        blob (per-page media allocator).
      * ``attstr_slots`` — the 88-entry attstr table mapping AppAttNames
        slot → page binattinf record index (or 0xffff).  Generated by the
        binattinf builder (``tft_attrs_encoder.build_component_block``).
    """

    init_off: int
    slot_offsets: list[int]   # exactly 5 entries (slots 1..5)
    objdatarampos: int
    attstr_bytecode_offset: int   # +52; == init_off when slot 0 present
    attstr_slots: list[int]   # exactly 88 entries (u16 each)


def type_flag(lei: int) -> int:
    """Return the +3 type-flag byte for a component class."""
    try:
        return TYPE_FLAG[lei]
    except KeyError:
        raise KeyError(
            f"no type-flag for lei={lei}; decode it from a reference TFT "
            f"(+3 byte of the objxinxi entry) and add it to TYPE_FLAG"
        ) from None


def geometry(lei: int, x: int, y: int, w: int, h: int) -> tuple[int, int, int, int, int, int]:
    """Return ``(x, y, w, h, endx, endy)`` for an objxinxi entry.

    Visual components store their authored box; ``endx = x + w - 1`` and
    ``endy = y + h - 1``.  Non-visual components (Timer / Variable) store
    the editor's 1×1-at-origin placeholder (``endx = endy = 0``)."""
    if lei in NONVISUAL_LEIS:
        return (0, 0, 1, 1, 0, 0)
    endx = x + w - 1 if w else 0
    endy = y + h - 1 if h else 0
    return (x, y, w, h, endx, endy)


def encode_objxinxi_entry(
    lei: int,
    comp_id: int,
    x: int,
    y: int,
    w: int,
    h: int,
    inputs: ObjxinxiInputs,
) -> bytes:
    """Assemble one 232-byte objxinxi entry.

    The HMI-derivable fields (lei, id, constants, type-flag, geometry) are
    generated here; the allocator / back-patch fields come from
    ``inputs``.  The result is byte-identical to the editor's entry when
    ``inputs`` carry the editor's offsets/record-indices."""
    if len(inputs.slot_offsets) != 5:
        raise ValueError("slot_offsets must have exactly 5 entries (slots 1..5)")
    if len(inputs.attstr_slots) != ATTSTR_SLOT_COUNT:
        raise ValueError(f"attstr_slots must have {ATTSTR_SLOT_COUNT} entries")

    gx, gy, gw, gh, endx, endy = geometry(lei, x, y, w, h)

    out = bytearray(OBJXINXI_ENTRY_SIZE)
    out[0] = lei & 0xFF
    out[1] = comp_id & 0xFF
    out[2] = CONST_AT_2
    out[3] = type_flag(lei)
    struct.pack_into("<I", out, 4, inputs.init_off & 0xFFFFFFFF)
    for i, off in enumerate(inputs.slot_offsets):
        struct.pack_into("<I", out, 8 + i * 4, off & 0xFFFFFFFF)
    struct.pack_into("<I", out, 28, inputs.objdatarampos & 0xFFFFFFFF)
    struct.pack_into("<I", out, 32, CONST_AT_32)
    struct.pack_into("<I", out, 36, CONST_AT_36)
    struct.pack_into("<HHHHHH", out, 40, gx & 0xFFFF, gy & 0xFFFF,
                     gw & 0xFFFF, gh & 0xFFFF, endx & 0xFFFF, endy & 0xFFFF)
    struct.pack_into("<I", out, 52, inputs.attstr_bytecode_offset & 0xFFFFFFFF)
    for i, rec_idx in enumerate(inputs.attstr_slots):
        struct.pack_into("<H", out, ATTSTR_SLOT_OFFSET + i * 2, rec_idx & 0xFFFF)
    return bytes(out)


