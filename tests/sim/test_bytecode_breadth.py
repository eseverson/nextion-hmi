# Every datafrom (RAM-backed) attribute's binattinf record stores
# `attmemorypos == objdatarampos + attposup`, so each fixture component
# byte-locks the attposup for its class.  The DATAFROM_ATTRS attposup values
# are already whole-block byte-verified (test_untested_components_binattinf
# / test_init_encoder_corpus); here we assert ATTPOSUP_TABLE_T1 agrees with
# them for every class the table claims, catching IL-misderivation.

_TASK6_LEIS = [0, 5, 55, 56, 57, 58, 112, 113, 122]


@pytest.mark.parametrize("lei", sorted(ATTPOSUP_TABLE_T1))
def test_attposup_table_matches_verified_binattinf(lei):
    """ATTPOSUP_TABLE_T1[lei] agrees with the byte-verified binattinf
    attposup (DATAFROM_ATTRS) for every attribute the two share.

    This locks the Task-6 IL-only entries (Curve/GText/CheckBox/Radio/
    Qrcode/Pic/Picc/Zhizhen) against their fixture oracles, and catches the
    two corrected `txt` spill offsets (GText 72, Qrcode 100)."""
    table = ATTPOSUP_TABLE_T1[lei]
    binattinf = {da.name: da.attposup for da in DATAFROM_ATTRS.get(lei, [])}
    shared = set(table) & set(binattinf)
    for name in sorted(shared):
        assert table[name] == binattinf[name], (
            f"lei {lei} attr {name!r}: ATTPOSUP_TABLE_T1={table[name]} "
            f"!= byte-verified binattinf={binattinf[name]}"
        )


def test_attposup_gtext_qrcode_txt_spill_corrected():
    """Regression: the GText(55)/Qrcode(58) `txt` offsets are the
    byte-verified spilled-Sstr values (72 / 100), not the raw in-struct IL
    field offsets (20 / 12)."""
    assert ATTPOSUP_TABLE_T1[55]["txt"] == 72
    assert ATTPOSUP_TABLE_T1[58]["txt"] == 100


def test_attposup_table_byte_verified_against_fixture():
    """Decode each Task-6 component's binattinf datafrom records straight
    from 03_untested-components/untested.tft and assert ATTPOSUP_TABLE_T1
    matches the on-disk attmemorypos - objdatarampos for every shared
    attribute (the direct fixture byte-lock)."""
    data, _strd, _objs, _flat = _untested_oracle()
    data, a1 = _tft_dirs(UNTESTED_TFT)
    strd = a1["strdataaddr"]
    objbase = a1["objxinxiadd"]
    pe = data[a1["pageadd"] + 3 * 16:a1["pageadd"] + 3 * 16 + 16]
    recbase = strd + struct.unpack_from("<I", pe, 8)[0]
    ep = load_hmi_pages(str(UNTESTED_HMI))[3]

    checked = 0
    for ci, c in enumerate(ep.components):
        if c.lei not in ATTPOSUP_TABLE_T1:
            continue
        table = ATTPOSUP_TABLE_T1[c.lei]
        stride, offmap = PER_LEI_LAYOUT[c.lei]
        e = data[objbase + (42 + ci) * 232:objbase + (42 + ci) * 232 + 232]
        slots = struct.unpack_from("<88H", e, 56)
        nz = [s for s in slots if s != 0xFFFF]
        if not nz:
            continue
        base = min(nz)
        for name in table:
            off = offmap.get(name)
            if off is None:
                continue
            rec = data[recbase + (base + off) * 24:
                       recbase + (base + off) * 24 + 24]
            objdr = struct.unpack_from("<I", rec, 0)[0]
            attmem = struct.unpack_from("<i", rec, 4)[0]
            assert attmem - objdr == table[name], (
                f"{c.name} lei {c.lei} attr {name!r}: fixture attposup "
                f"{attmem - objdr} != table {table[name]}"
            )
            checked += 1
    assert checked > 20, f"only byte-checked {checked} attposup entries"
