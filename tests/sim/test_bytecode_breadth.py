def _button_setbrush_blocks(style: int, borderw: int = 0):
    comp = Component(comp_type=98, comp_id=4, page_id=2, x=52, y=233,
                     w=100, h=50,
                     attrs={'sta': 1, 'style': style, 'spax': 0, 'spay': 0,
                            'borderw': borderw})
    blob = encode_init_block(comp, lambda n: _BTN_ADDRS[n])
    return disassemble_blocks_to_lines(blob)


def test_button_style1_borderw_inline_il_derived_unverified():
    """sta=1, style=1 → the setbrush trailing arg is the **borderw value**
    inlined as ASCII (borderw has attposup -1, a compile-time constant —
    NOT a LOAD).  No style=1 button fixture exists.  style=1 also omits the
    draw3d bevel (only style=4 emits it)."""
    blocks = _button_setbrush_blocks(style=1, borderw=3)
    heads = [b[:3] for _p, b in blocks]
    # no draw3d (09 07 08) for style != 4
    assert b"\x09\x07\x08" not in heads
    # both setbrush blocks (pressed/released) end with `,0,3` (borderw=3).
    setbrush_blocks = [b for _p, b in blocks if b[:3] == b"\x09\x1d\x08"]
    assert len(setbrush_blocks) == 2
    for sb in setbrush_blocks:
        assert sb[-4:] == b"\x2c\x30\x2c\x33", sb[-6:].hex()  # ,0,3


