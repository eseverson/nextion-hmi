def _ctx_with_globals(**names: int) -> CompileContext:
    ctx = CompileContext()
    for n, off in names.items():
        ctx.globals[n] = off
    return ctx


def test_and_connector_detection():
    assert condition_connector("a>1 && b>2") == "&&"
    assert condition_connector("a>1 || b>2") == "||"
    assert condition_connector("a>1") is None
    with pytest.raises(ValueError):
        condition_connector("a>1 && b>2 || c>3")


def test_and_chain_il_derived_unverified():
    """`if(a>1 && b>2){ sys0=1 }` — every clause keeps its natural
    comparator and skips past the body, so the body runs only when ALL
    clauses hold (AND short-circuit via the VM's "cjmp jumps on FAIL").

    Golden snapshot of the IL-derived encoding (no `&&` device oracle)."""
    ctx = _ctx_with_globals(sys0=0, a=4, b=8)
    out = compile_event_handler(
        "if(a>1 && b>2)\n{\nsys0=1\n}", ctx)
    expected = bytes.fromhex(
        # cjmp(a > 1)  endid 3, target +33 (skips 2nd cjmp + body)
        "12000000" "09000405040000002c312c332c0321000000"
        # cjmp(b > 2)  endid 3, target +11 (skips body)
        "12000000" "09000405080000002c322c332c030b000000"
        # body sys0=1
        "07000000" "05000000003d31"
    )
    assert out == expected, f"\n got {out.hex()}\n exp {expected.hex()}"


def test_and_chain_else_il_derived_unverified():
    """`if(a>1 && b>2){ sys0=1 } else { sys0=2 }` — both && clauses jump
    to the else branch on failure; the then-branch ends with a jmp over
    the else.  Golden snapshot (IL-derived, no oracle)."""
    ctx = _ctx_with_globals(sys0=0, a=4, b=8)
    out = compile_event_handler(
        "if(a>1 && b>2)\n{\nsys0=1\n}else\n{\nsys0=2\n}", ctx)
    # Decode the two leading cjmps + verify both skip to the else body
    # (same destination) and the then-body ends with a jmp-over-else.
    entries = []
    i = 0
    while i < len(out):
        ln = struct.unpack_from("<I", out, i)[0]
        entries.append(out[i + 4:i + 4 + ln])
        i += 4 + ln
    assert entries[0][:3] == b"\x09\x00\x04"   # cjmp a>1
    assert entries[1][:3] == b"\x09\x00\x04"   # cjmp b>2
    # cjmp targets (last 4 bytes, signed). Both land at the same absolute
    # byte position (else-body start), so target_b == target_a - len(cjmp_b).
    ta = struct.unpack("<i", entries[0][-4:])[0]
    tb = struct.unpack("<i", entries[1][-4:])[0]
    assert ta == tb + (len(entries[1]) + 4), (ta, tb)
    # there is a jmp-over-else (54 20 03) before the else body
    assert any(e[:3] == b"\x54\x20\x03" for e in entries)
    # Golden lock of the whole stream. Both cjmps land at the else body
    # (cjmp[0] tgt 44, cjmp[1] tgt 22); the then-body jmp skips the else
    # body (tgt 11).
    expected = bytes.fromhex(
        "12000000" "09000405040000002c312c332c032c000000"
        "12000000" "09000405080000002c322c332c0316000000"
        "07000000" "05000000003d31"
        "07000000" "5420030b000000"
        "07000000" "05000000003d32"
    )
    assert out == expected, f"\n got {out.hex()}\n exp {expected.hex()}"


