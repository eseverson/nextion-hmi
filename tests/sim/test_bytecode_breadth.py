def test_for_int_init_il_derived_unverified():
    """`for(int qq=0; qq<5; qq=qq+1){ sys0=qq }` — the `int qq=0` init
    declares the loop global AND emits the `qq=0` assignment run once at
    loop entry (findings/script-control-flow.md worked example 3).

    Golden snapshot of the IL-derived lowering (no `for` device oracle)."""
    ctx = _ctx_with_globals(sys0=0)   # sys0 = the project's first global
    out = compile_event_handler(
        "for(int qq=0; qq<5; qq=qq+1)\n{\nsys0=qq\n}", ctx)
    # qq is allocated AFTER sys0 → global offset 4.
    assert ctx.globals["qq"] == 4
    expected = bytes.fromhex(
        # qq=0  (init, runs once)
        "07000000" "05040000003d30"
        # cjmp(qq < 5)  endid 2, target +0x2b
        "12000000" "09000405040000002c352c322c032b000000"
        # body sys0=qq
        "0b000000" "05000000003d0504000000"
        # increment qq=qq+1
        "0d000000" "05040000003d05040000002b31"
        # back-jmp to the cjmp prefix (entry distance -4 → -65 bytes)
        "07000000" "542003bfffffff"
    )
    assert out == expected, f"\n got {out.hex()}\n exp {expected.hex()}"


def test_for_int_init_with_const_global():
    """The init also works when the loop var is pre-declared (no `int`
    keyword) — the non-`int` path is unchanged."""
    ctx = _ctx_with_globals(sys0=0, qq=4)
    out = compile_event_handler(
        "for(qq=0; qq<5; qq=qq+1)\n{\nsys0=qq\n}", ctx)
    # Same byte stream as the int-decl form (the init is just `qq=0`).
    assert out[:11] == bytes.fromhex("07000000" "05040000003d30")


