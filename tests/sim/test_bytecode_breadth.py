# Task 4 — GText secondary scroll blocks  (VERIFIED against 17.tft g0)
# ============================================================================

def test_gtext_scroll_blocks_verified():
    """The `09 24 08` scroll-init + `4c 20 03` motion-jmp blocks that arm
    GText scrolling, byte-verified against 17_more_components/17.tft g0.

    These follow g0's Ref setbrush+zstr blocks but belong to the slide
    event chain (firmware GuiGTextObjInit), not the Ref event."""
    data, a1 = _tft_dirs(F17)
    strd = a1["strdataaddr"]
    objs = parse_objxinxi(data, a1["objxinxiadd"], a1["objqyt"])
    g = next(o for o in objs if o.lei == 55)

    # Read the full live init chain; the last two blocks are the scroll pair.
    ab = strd + g.init_off
    pos = ab
    blocks = []
    while True:
        ln = struct.unpack_from("<I", data, pos)[0]
        if ln == 0 or ln > 0x300:
            break
        blocks.append(data[pos:pos + 4 + ln])
        pos += 4 + ln
    scroll_blk, motion_blk = blocks[-2], blocks[-1]
    assert scroll_blk[4:7] == b"\x09\x24\x08"
    assert motion_blk[4:7] == b"\x4c\x20\x03"

    # en/tim operands and the L addr, recovered from the live blocks.
    en_addr, tim_addr = _loads(scroll_blk)
    motion_addr = struct.unpack_from("<I", motion_blk, 7)[0]

    got = encode_gtext_scroll_blocks(
        lambda n: {"en": en_addr, "tim": tim_addr}[n], motion_addr)
    assert got == scroll_blk + motion_blk, (
        f"\n got {got.hex()}\n exp {(scroll_blk + motion_blk).hex()}"
    )


