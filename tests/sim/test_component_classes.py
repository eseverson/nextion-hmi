"""Whole-component generation for the remaining component classes (me/miata-dash#38).

The HMI→TFT compiler originally generated byte-exact output only for the 9
classes in the dash project (Page 121, Hotspot 109, XFloat 59, Text 116,
Prog 106, Slider 1, Button 98, Timer 51, Variable 52).  This suite proves the
compiler now generates EVERY remaining component class that appears in a real
editor fixture, block-for-block byte-exact against the oracle TFT:

    Curve/Waveform(0), Touchcap(5), Button_T(53), Number(54), GText(55),
    Checkbox(56), Radio(57), Qrcode(58), Pic(112), Picc(113), Zhizhen/Gauge(122)

Oracles (both version-'D' editor builds):
    tests/editor outputs/03_untested-components/untested.{HMI,tft}
    tests/editor outputs/_old/17_more_components/17.{HMI,tft}

Each component's GENERATED blocks are asserted byte-identical to the matching
span parsed out of the oracle TFT:

  * **objxinxi entry header** — type-flag (+3), geometry (+40..+52), and the
    88-slot attstr record-index table (+56);
  * **event-region stream** — the whole per-component EVENT_LAYOUT expansion
    (init slot-0 bytecode, the auto-fill + overlap cross-redraw refs, the
    toggle / scroll handlers, and the event-name strings);
  * **frame ``<Kind>_PARAM`` block** — for the 8 classes whose block has no
    Sstr/molloc spill (Number, Pic, Picc, Zhizhen, CheckBox, Radio, Button_T,
    Touchcap).  The 3 spill classes (Qrcode/GText/Curve) carry a per-page
    Sstr/molloc spill region after the frame blocks whose framing holds
    non-content-derivable editor draw-brush scratch (``de ff`` + the
    ``0x2946`` back-colour + a save-varying step literal — it differs between
    two saves of an identical component), so their *whole-file* round-trip is
    NOT byte-reproducible; their in-block struct fields (everything except the
    spill pointer) ARE verified here.

``test_binattinf_*`` records are covered by ``test_untested_components_binattinf``
(untested) and the bytecode-breadth suite; this file adds the objxinxi /
event-stream / frame coverage that completes whole-component generation.
"""
