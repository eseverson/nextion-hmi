UNTESTED = REPO_ROOT / "tests" / "editor outputs" / "03_untested-components"
MORE = REPO_ROOT / "tests" / "editor outputs" / "_old" / "17_more_components"

FIXTURES = [
    (UNTESTED / "untested.HMI", UNTESTED / "untested.tft", FRAME_PREFIX_D),
    (MORE / "17.HMI", MORE / "17.tft", FRAME_PREFIX),
]

# The classes me/miata-dash#38 adds (beyond the original 9).
NEW_LEIS = {0, 5, 53, 54, 55, 56, 57, 58, 112, 113, 122}


def _dirs(data):
    mc = int.from_bytes(data[0x2E:0x32], "little")
    return parse_appinf1_corrected(h2_decrypt(data[0xC8:0xC8 + 196], mc))


def _oracle_components(hmi_path, tft_path, frame_prefix):
    """Yield ``(name, lei, ci, pi, hc, oracle_objxinxi, oracle_event_stream,
    oracle_frame_block)`` for every NEW-class component in the fixture."""
    data = tft_path.read_bytes()
    a1 = _dirs(data)
    strd, objbase, pageadd = a1["strdataaddr"], a1["objxinxiadd"], a1["pageadd"]
    hmi = load_hmi_pages(str(hmi_path))
    pshift = project_global_shift(hmi)
    profile = profile_for(data, **project_scratch_for(data, hmi))
    attstr = _generated_attstr_slots(hmi)
    counts = page_record_counts(hmi)
    cum = [sum(counts[:i]) for i in range(len(counts) + 1)]

    out = []
    for pi, hp in enumerate(hmi):
        pe = data[pageadd + pi * 16:pageadd + pi * 16 + 16]
        objstar = struct.unpack_from("<H", pe, 0)[0]
        hexpos = struct.unpack_from("<I", pe, 4)[0]
        po = attstr[pi]
        base = cum[pi]
        page_bco = base + po[0].slots[APP_ATT_NAMES.index("bco")]
        attr_offs = build_page_attr_offsets(hp.components, po, base)
        orefs = page_overlap_refs(hp.components)
        gtrefs = page_global_text_refs(hp.components)

        # event-stream start offsets (attstr_bytecode_offset) + media start.
        starts = [
            struct.unpack_from(
                "<I", data[objbase + (objstar + ci) * 232:
                           objbase + (objstar + ci) * 232 + 232], 52)[0]
            for ci in range(len(hp.components))
        ]
        starts.append(hexpos)

        # frame image base + per-object block offsets (page block first).
        lay = layout_from_hmi_page(hp, frame_prefix, pshift)
        nh = build_page_name_hash_table(hp, lay.medatapos)
        fb = strd + hexpos + len(nh)
        pb = build_page_block(len(hp.components), hp.page_attrs)
        fcur = len(pb)
        frame_at = {}
        for ci, hc in enumerate(hp.components):
            if ci == 0:
                continue
            sz = SIZEOF_OBJDATA_T1.get(hc.lei, 0)
            frame_at[ci] = data[fb + fcur:fb + fcur + sz]
            fcur = (fcur + sz + 3) & ~3

        for ci, hc in enumerate(hp.components):
            if hc.lei not in NEW_LEIS:
                continue
            oi = objstar + ci
            objx = data[objbase + oi * 232:objbase + oi * 232 + 232]
            # Skip STALE fixture entries — components whose .HMI geometry does
            # not match the compiled .tft (the editor edited the HMI after the
            # TFT was produced, so this TFT is not the HMI's compile output).
            # 17_more_components has two such page-3 components (q0/bt0); the
            # untested fixture is a clean matched pair (0 mismatches).  A stale
            # entry can't be a byte-exact oracle for its own HMI.
            a = hc.attrs
            gx = 0 if ci == 0 else int(a.get("x") or 0)
            gy = 0 if ci == 0 else int(a.get("y") or 0)
            gw = int(a.get("w") or 0)
            gh = int(a.get("h") or 0)
            if geometry(hc.lei, gx, gy, gw, gh) != struct.unpack_from(
                    "<6H", objx, 40):
                continue
            event = data[strd + starts[ci]:strd + starts[ci + 1]]
            cc = build_component_chains(
                hc, list(po[ci].slots), base, page_bco, hp.page_id,
                attr_offs, orefs.get(hc.name), profile=profile,
                prefix_ids=gtrefs.get(hc.name))
            gen_event, _, _ = _emit_component_event(cc, starts[ci])
            out.append((
                hc.name, hc.lei, ci, pi, hc, objx, event, gen_event,
                frame_at.get(ci, b""), attstr[pi][ci].slots,
            ))
    return out


def _all_components():
    seen = {}
    for hmi_path, tft_path, fp in FIXTURES:
        for rec in _oracle_components(hmi_path, tft_path, fp):
            seen.setdefault((rec[1], tft_path.name), rec)
    return list(seen.values())


_COMPONENTS = _all_components()
_IDS = [f"lei{r[1]}_{r[0]}_{r[3]}" for r in _COMPONENTS]


def test_every_new_class_present():
    """Both fixtures together exercise all 11 new component classes."""
    leis = {r[1] for r in _COMPONENTS}
    assert NEW_LEIS <= leis, f"missing classes: {NEW_LEIS - leis}"


@pytest.mark.parametrize("rec", _COMPONENTS, ids=_IDS)
def test_objxinxi_header_byte_identical(rec):
    """The generated objxinxi type-flag + geometry + attstr-slot table match."""
    name, lei, ci, pi, hc, objx, *_rest = rec
    attstr_slots = rec[9]
    a = hc.attrs
    assert objx[3] == type_flag(lei), f"{name}: type-flag"
    x = 0 if ci == 0 else int(a.get("x") or 0)
    y = 0 if ci == 0 else int(a.get("y") or 0)
    w = int(a.get("w") or 0)
    h = int(a.get("h") or 0)
    assert struct.unpack_from("<6H", objx, 40) == geometry(lei, x, y, w, h), \
        f"{name}: geometry"
    assert tuple(attstr_slots) == struct.unpack_from("<88H", objx, 56), \
        f"{name}: attstr slot table"


@pytest.mark.parametrize("rec", _COMPONENTS, ids=_IDS)
def test_event_stream_byte_identical(rec):
    """The generated per-component event-region stream (init + auto-fill +
    handlers + name strings) matches the oracle byte-for-byte."""
    name, lei, ci, pi = rec[0], rec[1], rec[2], rec[3]
    oracle_event, gen_event = rec[6], rec[7]
    assert gen_event == oracle_event, (
        f"{name} (lei {lei}) event stream diverges: "
        f"{len(gen_event)} vs {len(oracle_event)} bytes")


# Non-spill classes: the whole frame block is byte-derivable.
_NONSPILL = [r for r in _COMPONENTS if r[1] not in SPILL_CLASSES]
_NONSPILL_IDS = [f"lei{r[1]}_{r[0]}_{r[3]}" for r in _NONSPILL]


@pytest.mark.parametrize("rec", _NONSPILL, ids=_NONSPILL_IDS)
def test_nonspill_frame_block_byte_identical(rec):
    """For the 8 classes whose frame block has no Sstr/molloc spill, the
    generated ``<Kind>_PARAM`` block is byte-identical to the oracle's."""
    name, lei = rec[0], rec[1]
    oracle_block = rec[8]
    if not oracle_block:           # SIZEOF 0 (none here, but be safe)
        pytest.skip("no frame block")
    gen = bytes(build_object_block(lei, rec[4].attrs))[:len(oracle_block)]
    assert gen == oracle_block, (
        f"{name} (lei {lei}) frame block diverges: "
        f"gen {gen.hex()} != oracle {oracle_block.hex()}")


# Spill classes: verify every in-block field EXCEPT the spill pointer (which
# depends on the per-page spill layout and is back-patched, not struct-local).
_SPILL = [r for r in _COMPONENTS if r[1] in SPILL_CLASSES]
_SPILL_IDS = [f"lei{r[1]}_{r[0]}_{r[3]}" for r in _SPILL]

# Byte ranges within each spill class's frame block that hold the spill
# pointer(s) — excluded from the in-block comparison (back-patched).
_SPILL_PTR_BYTES = {
    58: range(12, 16),                       # Qrcode txt_ptr @12 (16-byte block)
    55: range(20, 24),                       # GText txt_ptr @20 (36-byte block)
    0: list(range(28, 32)) + list(range(32, 36)),  # Curve molloc_s @28 / molloc @32
}


@pytest.mark.parametrize("rec", _SPILL, ids=_SPILL_IDS)
def test_spill_frame_block_inblock_fields(rec):
    """Qrcode/GText/Curve: every in-block ``<Kind>_PARAM`` field matches the
    oracle EXCEPT the spill pointer (back-patched from the per-page spill
    region, which carries non-content-derivable editor scratch — see module
    docstring)."""
    name, lei = rec[0], rec[1]
    oracle_block = rec[8]
    gen = bytes(build_object_block(lei, rec[4].attrs))[:len(oracle_block)]
    ptr_bytes = set(_SPILL_PTR_BYTES[lei])
    diffs = [i for i in range(len(oracle_block))
             if i not in ptr_bytes and gen[i] != oracle_block[i]]
    assert not diffs, (
        f"{name} (lei {lei}) in-block fields diverge at {diffs}: "
        f"gen {gen.hex()} vs oracle {oracle_block.hex()}")
